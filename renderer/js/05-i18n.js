let currentLang = 'zh';
try { currentLang = localStorage.getItem('data-bench-lang') || 'zh'; } catch (e) { /* ignore */ }

function t(key) {
  const d = I18N_DICT[currentLang] || I18N_DICT.zh;
  return d[key] !== undefined ? d[key] : (I18N_DICT.zh[key] !== undefined ? I18N_DICT.zh[key] : key);
}

function setLanguage(lang) {
  currentLang = lang;
  try { localStorage.setItem('data-bench-lang', lang); } catch (e) { /* ignore */ }
  applyStaticI18n();
  buildTree();
}

function applyStaticI18n() {
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.getAttribute('data-i18n-title')); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.getAttribute('data-i18n-placeholder')); });
}
